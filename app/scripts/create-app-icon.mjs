import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {Atom} from '@phosphor-icons/react';
import {Resvg} from '@resvg/resvg-js';
import {mkdir,writeFile} from 'node:fs/promises';
const icon=renderToStaticMarkup(React.createElement(Atom,{size:180,weight:'light',color:'#bde3ea'}));
const svg=`<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256"><rect width="256" height="256" rx="50" fill="#11191f"/><g transform="translate(38,38)">${icon}</g></svg>`;
const png=Buffer.from(new Resvg(svg).render().asPng());
await mkdir(new URL('../electron/assets/',import.meta.url),{recursive:true});
await writeFile(new URL('../electron/assets/icon.png',import.meta.url),png);
const header=Buffer.alloc(22);header.writeUInt16LE(1,2);header.writeUInt16LE(1,4);header.writeUInt16LE(1,10);header.writeUInt16LE(32,12);header.writeUInt32LE(png.length,14);header.writeUInt32LE(22,18);
await writeFile(new URL('../electron/assets/icon.ico',import.meta.url),Buffer.concat([header,png]));
console.log('Created PulseDeck app icons from the Phosphor Atom icon.');
